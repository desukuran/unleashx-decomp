#!/usr/bin/env python3
"""Generate C struct declarations from layout files in symbols/structs/.

Each file describes one struct:

    struct CAppSettings 0x191c        # name and total size
    0x000 void* vftable
    0x0c28 std_string m_strDashPath   # comment
    0x14c0 BOOL m_bWidescreen
    0x1818 char m_szName[32]

Fields may be listed in any order; gaps become padding. Writes
build/structs.h, which tools/apply.sh appends to symbols/types.h.
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SIZES = {
    'char': 1, 'BYTE': 1, 'bool': 1, 'WORD': 2, 'short': 2, 'wchar_t': 2,
    'int': 4, 'DWORD': 4, 'BOOL': 4, 'float': 4, 'long': 4, 'HANDLE': 4,
    'double': 8, 'std_string': 0x1c, 'std_wstring': 0x1c, 'std_vector': 0x10,
    'CObList': 0x1c, 'CXmlElement': 0xd4, 'CXmlDocument': 0x11c,
}


def type_size(t, known):
    t = t.strip()
    if t.endswith('*'):
        return 4
    if t in SIZES:
        return SIZES[t]
    if t in known:
        return known[t]
    raise ValueError(f'unknown size for type {t!r}')


def parse(path):
    name, size, fields = None, None, []
    for raw in open(path):
        line = raw.split('#', 1)[0].strip()
        if not line:
            continue
        if line.startswith('struct '):
            _, name, size = line.split()
            size = int(size, 16)
            continue
        m = re.match(r'(0x[0-9a-fA-F]+)\s+(.+?)\s*([A-Za-z_]\w*)\s*(\[(\w+)\])?$', line)
        if not m:
            raise ValueError(f'{path}: bad line {raw!r}')
        off, typ, fname, _, count = m.groups()
        fields.append((int(off, 16), typ.replace(' ', ''), fname, int(count, 0) if count else None))
    fields.sort()
    return name, size, fields


def main():
    out = ['/* Generated by tools/gen_structs.py from symbols/structs/ -- do not edit */', '']
    known = {}
    for path in sorted(glob.glob(os.path.join(ROOT, 'symbols/structs/*.txt'))):
        name, size, fields = parse(path)
        out.append(f'typedef struct {name} {{')
        pos = 0
        for off, typ, fname, count in fields:
            if off < pos:
                sys.exit(f'{path}: {fname} at {off:#x} overlaps previous field (ends {pos:#x})')
            if off > pos:
                out.append(f'\tBYTE _pad{pos:04x}[{off - pos:#x}];')
            n = type_size(typ, known) * (count or 1)
            out.append(f'\t{typ} {fname}{f"[{count}]" if count else ""}; /* +{off:#x} */')
            pos = off + n
        if pos > size:
            sys.exit(f'{path}: fields end at {pos:#x}, past size {size:#x}')
        if pos < size:
            out.append(f'\tBYTE _pad{pos:04x}[{size - pos:#x}];')
        out.append(f'}} {name};')
        out.append('')
        known[name] = size
    os.makedirs(os.path.join(ROOT, 'build'), exist_ok=True)
    with open(os.path.join(ROOT, 'build/structs.h'), 'w') as f:
        f.write('\n'.join(out))


if __name__ == '__main__':
    main()
