#!/usr/bin/env python3
"""Generate symbols/rtti.txt from recovered RTTI.

  gen_rtti_symbols.py <xbe> <functions.tsv> <out.txt>

Names vtables (Class::vftable), virtual methods (Class::vfuncN, assigned to the
most-base class that owns the slot), the scalar deleting destructor in slot 0
(Class::`scalar deleting destructor'), and constructors/destructors found by
scanning functions for stores of the class's vtable address.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from capstone import Cs, CS_ARCH_X86, CS_MODE_32  # noqa: E402
from capstone.x86 import X86_OP_IMM, X86_OP_MEM  # noqa: E402

from rtti import recover  # noqa: E402
from xbe import Xbe  # noqa: E402


def load_functions(path):
    funcs = []
    with open(path) as f:
        next(f)
        for line in f:
            addr, size, block, name = line.split('\t')[:4]
            if block == '.text':
                funcs.append((int(addr, 16), int(size), name))
    return funcs


def safe(name):
    return name.replace(' ', '_')


def main():
    x = Xbe(sys.argv[1])
    classes = [c for c in recover(x) if not c['name'].startswith(('.', 'std::'))]
    funcs = load_functions(sys.argv[2])
    img = x.flat_image()
    u32 = lambda va: struct.unpack_from('<I', img, va - x.base)[0]

    syms = {}  # address -> name; first writer wins, so order matters

    def put(addr, name):
        syms.setdefault(addr, name)

    vt_owner = {}
    for c in classes:
        for v in c['vtables']:
            suffix = '' if v['offset'] == 0 else f"_{v['offset']}"
            put(v['address'], f"{c['name']}::vftable{suffix}")
            vt_owner[v['address']] = c['name']

    # Slot ownership: process classes from the shallowest hierarchy depth so a
    # slot function shared with a base keeps the base's name.
    depth = {c['name']: len(c['bases']) for c in classes}
    for c in sorted(classes, key=lambda c: (depth[c['name']], c['name'])):
        for v in c['vtables']:
            for i, f in enumerate(v['slots']):
                if i == 0 and v['offset'] == 0:
                    put(f, f"{c['name']}::`scalar_deleting_destructor'")
                else:
                    put(f, f"{c['name']}::vfunc{i}" if v['offset'] == 0 else f"{c['name']}::vfunc{i}_{v['offset']}")

    # Ctor/dtor scan: "mov dword ptr [reg(+off)], imm32" where imm32 is a vtable.
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    md.detail = True
    sdd = {}  # class -> scalar deleting destructor address
    for c in classes:
        for v in c['vtables']:
            if v['offset'] == 0 and v['slots']:
                sdd[c['name']] = v['slots'][0]
    writes = {}  # func -> set of classes whose primary vtable it stores
    calls = {}   # func -> set of call targets
    for addr, size, name in funcs:
        code = img[addr - x.base:addr - x.base + size]
        for ins in md.disasm(code, addr):
            if ins.mnemonic == 'mov' and len(ins.operands) == 2:
                dst, src = ins.operands
                if (dst.type == X86_OP_MEM and dst.mem.disp == 0 and src.type == X86_OP_IMM
                        and (src.imm & 0xFFFFFFFF) in vt_owner):
                    writes.setdefault(addr, []).append(vt_owner[src.imm & 0xFFFFFFFF])
            elif ins.mnemonic == 'call' and ins.operands[0].type == X86_OP_IMM:
                calls.setdefault(addr, set()).add(ins.operands[0].imm)

    bases = {c['name']: {b['name'] for b in c['bases']} for c in classes}
    for addr, owners in writes.items():
        # Only treat it as a ctor/dtor if every store belongs to one hierarchy;
        # otherwise it's code that inlines several unrelated constructors.
        top = max(owners, key=lambda o: len(bases[o]))
        if any(o != top and o not in bases[top] for o in owners):
            continue
        # The last vtable stored is the most-derived one in a ctor; in a dtor the
        # first store is the class itself (bases are reset afterwards in callees).
        cls_ctor, cls_dtor = owners[-1], owners[0]
        if addr in calls.get(sdd.get(cls_dtor, -1), set()):
            put(addr, f"{cls_dtor}::~{cls_dtor.split('::')[-1]}")
        elif addr not in syms:
            put(addr, f"{cls_ctor}::{cls_ctor.split('::')[-1]}")

    with open(sys.argv[3], 'w') as f:
        f.write('# Generated by tools/gen_rtti_symbols.py -- do not edit; put overrides in symbols/names.txt\n')
        for a in sorted(syms):
            f.write(f'{a:08x} {safe(syms[a])}\n')
    print(f'{len(syms)} symbols, {len(classes)} classes')


if __name__ == '__main__':
    main()
