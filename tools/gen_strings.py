#!/usr/bin/env python3
"""Generate src/ui/StringIds.h and src/ui/StringTable.inc from symbols/strings.json.

symbols/strings.json was extracted from the switch in GetDefaultString
(0x0013A679): for each string ID, the language-file key and the built-in
English text.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def c_string(s):
    out = []
    for ch in s:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\r':
            out.append('\\r')
        elif ch == '\t':
            out.append('\\t')
        elif ord(ch) < 32 or ord(ch) > 126:
            out.append('\\x%02x' % ord(ch))
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


def main():
    entries = json.load(open(os.path.join(ROOT, 'symbols/strings.json')))
    last = max(e['id'] for e in entries)
    with open(os.path.join(ROOT, 'src/ui/StringIds.h'), 'w') as f:
        f.write('// Generated by tools/gen_strings.py from symbols/strings.json -- do not edit.\n')
        f.write('// UI string IDs; the names are the language-file keys (English.xml).\n#pragma once\n\n')
        f.write('enum StringId\n{\n')
        for e in entries:
            f.write(f'\tSTR_{e["key"]} = {e["id"]},\n')
        f.write(f'\tSTR_COUNT = {last + 1},\n}};\n')
    with open(os.path.join(ROOT, 'src/ui/StringTable.inc'), 'w') as f:
        f.write('// Generated by tools/gen_strings.py from symbols/strings.json -- do not edit.\n')
        f.write('// { id, language-file key, built-in English text }\n')
        for e in entries:
            f.write(f'{{{e["id"]}, {c_string(e["key"])}, {c_string(e["text"])}}},\n')
    with open(os.path.join(ROOT, 'docs/LANGUAGE_STRINGS.md'), 'w') as f:
        f.write('# UI strings\n\n')
        f.write('Generated by `tools/gen_strings.py` from the string table in the XBE (`GetDefaultString`, `0x0013A679`).\n\n')
        f.write('A language file (`<LanguageFile>` in Config.xml) is XML in the form `<Resource Name="..."><KEY>text</KEY>...</Resource>`. ')
        f.write('Any key left out keeps its English text, and `\\n` in a value is a line break. ')
        f.write('This table lists every key UnleashX 0.39.0528A looks up, including ones missing from the English.xml it shipped with.\n\n')
        f.write('| ID | Key | English |\n|---|---|---|\n')
        for e in entries:
            text = e['text'].replace('|', '\\|').replace('\n', '<br>')
            f.write(f'| {e["id"]} | `{e["key"]}` | {text} |\n')


if __name__ == '__main__':
    main()
