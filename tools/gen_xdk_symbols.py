#!/usr/bin/env python3
"""Convert XbSymbolDatabaseCLI output into symbols/xdk.txt.

  XbSymbolDatabaseCLI Default.xbe -e > build/xbsymbols.txt
  gen_xdk_symbols.py build/xbsymbols.txt symbols/xdk.txt

XbSymbolDatabase (MIT, github.com/Cxbx-Reloaded/XbSymbolDatabase) finds XDK
library functions/variables by signature. Lines look like
  D3D8__FUN__stdcall__D3DDevice_SetRenderStateNotInline(psh State, psh Value) = 0x0013fda0
  D3D8__FUN__fastcall__D3DDevice_SetRenderState_Simple(ecx Method, edx Value) = 0x0013fd70
  D3D8__VAR__D3D_g_pDevice = 0x00150ca8
"psh" parameters are pushed on the stack; register names pin a parameter.
"""
import re
import sys

LINE = re.compile(r'(\w+?)__(FUN|VAR)__(?:(\w+?)__)?(\w+)(?:\((.*)\))?\s*=\s*0x([0-9a-fA-F]+)')


def main():
    out = {}
    for line in open(sys.argv[1]):
        m = LINE.match(line.strip())
        if not m:
            continue
        lib, kind, conv, name, params, addr = m.groups()
        addr = int(addr, 16)
        if kind == 'VAR':
            out[addr] = f'{addr:08x} {name} data'
            continue
        args = []
        for i, p in enumerate(x.strip() for x in (params or '').split(',') if x.strip()):
            where, pname = p.split(None, 1)
            if where == 'psh':
                args.append(f'DWORD {pname}')
            elif where == 'ecx' and conv == 'thiscall':
                args.append(f'void *{pname}@ecx')
            elif where in ('al', 'bl', 'cl', 'dl', 'ah', 'bh', 'ch', 'dh'):
                args.append(f'BYTE {pname}@{where}')
            else:
                args.append(f'DWORD {pname}@{where}')
        cc = {'stdcall': '__stdcall', 'cdecl': '__cdecl'}.get(conv, '')
        if any('@' in a for a in args):
            cc = ''  # custom storage handles registers
        sig = f'DWORD {cc} f({", ".join(args) if args else "void"})'.replace('  ', ' ')
        out[addr] = f'{addr:08x} {name} {sig}'
    with open(sys.argv[2], 'w') as f:
        f.write('# Generated by tools/gen_xdk_symbols.py from XbSymbolDatabase -- do not edit\n')
        for a in sorted(out):
            f.write(out[a] + '\n')
    print(f'{len(out)} symbols')


if __name__ == '__main__':
    main()
